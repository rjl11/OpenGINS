#!/usr/bin/env python3
"""Cut a geoid grid down to an area around a point and write it as a C table.

The input is a GRAVSOFT-style text grid such as Lantmäteriet's
SWEN17_RH2000.txt: a header "lat_south lat_north lon_west lon_east dlat dlon"
(degrees), then the heights in metres, row by row from the north edge
southwards, each row from west to east.

The output (firmware/app/geoid_grid.c) holds the cut-out rows from south to
north as int16 millimetres from an offset, read by firmware/app/geoid.c.

    python firmware/tools/geoid_cut.py geoid/SWEN17_RH2000.txt \\
        --lat <base latitude> --lon <base longitude> --radius-km 100 -o firmware/app/geoid_grid.c
"""
import argparse
import math
import os


def read_grid(path):
    with open(path) as f:
        hdr = [float(x) for x in f.readline().split()]
        vals = [float(x) for x in f.read().split()]
    lat_s, lat_n, lon_w, lon_e, dlat, dlon = hdr
    rows = round((lat_n - lat_s) / dlat) + 1
    cols = round((lon_e - lon_w) / dlon) + 1
    if len(vals) != rows * cols:
        raise SystemExit(f"{path}: {len(vals)} values, header says {rows} x {cols}")
    return hdr, rows, cols, vals


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("grid")
    ap.add_argument("--lat", type=float, required=True, help="centre latitude, degrees")
    ap.add_argument("--lon", type=float, required=True, help="centre longitude, degrees")
    ap.add_argument("--radius-km", type=float, default=100.0)
    ap.add_argument("--name", default=None, help="model name (default: file name)")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    (lat_s, lat_n, lon_w, lon_e, dlat, dlon), rows, cols, vals = read_grid(a.grid)
    name = a.name or os.path.splitext(os.path.basename(a.grid))[0]

    # A box that holds the circle: one degree of latitude is about 111.2 km.
    half_lat = a.radius_km / 111.2
    half_lon = a.radius_km / (111.32 * math.cos(math.radians(a.lat)))
    # Grid indices counted from the south and west edges, widened to whole cells.
    r0 = max(0, math.floor((a.lat - half_lat - lat_s) / dlat))
    r1 = min(rows - 1, math.ceil((a.lat + half_lat - lat_s) / dlat))
    c0 = max(0, math.floor((a.lon - half_lon - lon_w) / dlon))
    c1 = min(cols - 1, math.ceil((a.lon + half_lon - lon_w) / dlon))
    nr, nc = r1 - r0 + 1, c1 - c0 + 1

    def at(r_south, c):  # the file runs north to south
        return vals[(rows - 1 - r_south) * cols + c]

    cut = [[at(r, c) for c in range(c0, c1 + 1)] for r in range(r0, r1 + 1)]
    lo = min(min(row) for row in cut)
    hi = max(max(row) for row in cut)
    offset = round((lo + hi) / 2, 1)
    mm = [[round((v - offset) * 1000) for v in row] for row in cut]
    if max(abs(v) for row in mm for v in row) > 32767:
        raise SystemExit(f"heights {lo:.3f}..{hi:.3f} m don't fit int16 mm around {offset} m")

    with open(a.out, "w", newline="\n") as f:
        f.write(f"/* Generated by firmware/tools/geoid_cut.py from {os.path.basename(a.grid)}, do not edit.\n")
        # Whole degrees (truncated): the header is in the repo, so it should not give the exact centre.
        f.write(f" * Area: {a.radius_km:g} km around {math.floor(a.lat)}N {math.floor(a.lon)}E, "
                f"{nr} x {nc} points, heights {lo:.3f}..{hi:.3f} m. */\n\n")
        f.write('#include "geoid.h"\n\n')
        f.write(f"static const int16_t s_mm[{nr} * {nc}] = {{\n")
        for row in mm:
            for i in range(0, nc, 12):
                f.write("    " + ", ".join(str(v) for v in row[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("const geoid_grid_t geoid_grid = {\n")
        f.write(f'    .name     = "{name}",\n')
        f.write(f"    .lat0_deg = {lat_s + r0 * dlat:.6f},\n")
        f.write(f"    .lon0_deg = {lon_w + c0 * dlon:.6f},\n")
        f.write(f"    .dlat_deg = {dlat:.6f},\n")
        f.write(f"    .dlon_deg = {dlon:.6f},\n")
        f.write(f"    .rows     = {nr},\n")
        f.write(f"    .cols     = {nc},\n")
        f.write(f"    .offset_m = {offset:.1f}f,\n")
        f.write("    .mm       = s_mm,\n")
        f.write("};\n")
    print(f"{a.out}: {nr} x {nc} points ({nr * nc * 2 / 1024:.0f} KB), "
          f"lat {lat_s + r0 * dlat:.2f}..{lat_s + r1 * dlat:.2f}, "
          f"lon {lon_w + c0 * dlon:.2f}..{lon_w + c1 * dlon:.2f}, heights {lo:.3f}..{hi:.3f} m")


if __name__ == "__main__":
    main()
